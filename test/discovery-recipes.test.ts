describe('guided-discovery catalog', () => {
  it('ships exactly three immutable, valid recipes with at most two branches each', () => {
    expect(DISCOVERY_RECIPES.map((recipe) => recipe.id)).toEqual([
      'climate-shock-specialists',
      'armor-stinger-contact',
      'leaf-mouth-shade',
    ]);
    validateDiscoveryCatalog(DISCOVERY_RECIPES);
    for (const recipe of DISCOVERY_RECIPES) {
      expect(discoverySupported(recipe)).toBe(true);
      expect(recipe.branches.length).toBeLessThanOrEqual(2);
      expect(recipe.horizonTick).toBeLessThanOrEqual(DISCOVERY_MAX_TICKS);
      expect(recipe.question.length).toBeGreaterThan(20);
      expect(recipe.limitations.join(' ')).toMatch(/not evidence across independent runs/);
      expect(Object.isFrozen(recipe.starts[0].designs[0].cells[0])).toBe(true);
      expect(readDiscoveryRecipe(JSON.stringify(recipe))).toEqual(recipe);
    }
    expect(DISCOVERY_MAX_TICKS).toBe(COMPARISON_MAX_TICKS);
    expect(() => ((DISCOVERY_RECIPES as DiscoveryRecipe[]).length = 0)).toThrow();
    expect(() => ((DISCOVERY_RECIPES[0] as any).horizonTick = 9000)).toThrow();
    expect(() => ((DISCOVERY_RECIPES[0].branches[1] as any).intervention = 'cold')).toThrow();
    expect(discoveryRecipe('leaf-mouth-shade')).toBe(DISCOVERY_RECIPES[2]);
    expect(() => discoveryRecipe('free-food')).toThrow('Unknown discovery recipe');
    expect(Object.keys(DISCOVERY_OUTCOMES).sort()).toEqual(
      ['completed', 'extinct', 'incomplete', 'missing-evidence', 'unsupported-rules'].sort(),
    );
  });

  it('preflights the combined session budget against current experiment limits', () => {
    for (const recipe of DISCOVERY_RECIPES) {
      const budget = discoveryBudget(recipe);
      expect(budget.engines).toBe(2);
      expect(budget.engineTicks).toBe(2 * recipe.horizonTick);
      expect(budget.samples).toBe(2 * discoverySampleTicks(recipe.horizonTick).length);
      expect(budget.retainedBytes).toBeLessThanOrEqual(RECIPE_MAX_BYTES);
      expect(budget.retainedBytes).toBeGreaterThan(2 * WORLD_MAX_BYTES);
    }
    expect(discoverySampleTicks(3600)).toHaveLength(121);
    expect(discoverySampleTicks(45)).toEqual([0, 30, 45]);
  });

  it('rejects the full catalog shape when count or identity are wrong', () => {
    expect(() => validateDiscoveryCatalog(DISCOVERY_RECIPES.slice(0, 2))).toThrow('exactly three');
    expect(() => validateDiscoveryCatalog([...DISCOVERY_RECIPES, DISCOVERY_RECIPES[0]])).toThrow(
      'exactly three',
    );
    expect(() =>
      validateDiscoveryCatalog([DISCOVERY_RECIPES[0], DISCOVERY_RECIPES[1], DISCOVERY_RECIPES[0]]),
    ).toThrow('unique');
    expect(() => validateDiscoveryCatalog({} as any)).toThrow('exactly three');
  });
});

