describe('real-engine starting states', () => {
  it('rebuild repeatably and match their recorded bytes, SHA-256 and population', () => {
    for (const recipe of DISCOVERY_RECIPES)
      for (const start of recipe.starts) {
        const text = buildDiscoveryStart(recipe, start.id);
        expect(buildDiscoveryStart(recipe, start.id)).toBe(text);
        expect(node(text)).toBe(start.checkpoint.sha256);
        expect(new TextEncoder().encode(text).byteLength).toBe(start.checkpoint.bytes);
        const world = Ecosystem.load(text);
        expect(world.tick).toBe(0);
        expect(world.settings).toEqual(start.settings);
        expect(world.organisms.size).toBe(start.placements.length);
        expect(world.nutrientCycle).toBeNull();
        expect(world.biologicalShade.enabled).toBe(false);
        expect(JSON.stringify(world.save())).toBe(text);
      }
  });

  it('refuse tampered constructions, provenance, unsupported rules and unknown states', () => {
    const moved = copy(DISCOVERY_RECIPES[2]);
    moved.starts[0].placements[0].x++;
    expect(() => buildDiscoveryStart(moved, 'producers-grazers')).toThrow('SHA-256 provenance');
    const resized = copy(DISCOVERY_RECIPES[2]);
    resized.starts[0].checkpoint.bytes++;
    expect(() => buildDiscoveryStart(resized, 'producers-grazers')).toThrow('SHA-256 provenance');
    const counted = copy(DISCOVERY_RECIPES[2]);
    counted.starts[0].checkpoint.population = 9;
    expect(() => buildDiscoveryStart(counted, 'producers-grazers')).toThrow('recorded population');
    const overlapping = copy(DISCOVERY_RECIPES[2]);
    overlapping.starts[0].placements[1] = { ...overlapping.starts[0].placements[0] };
    expect(() => buildDiscoveryStart(overlapping, 'producers-grazers')).toThrow(
      'placement 2 does not fit',
    );
    const future = copy(DISCOVERY_RECIPES[0]);
    future.rules.worldVersion++;
    expect(discoverySupported(future)).toBe(false);
    expect(() => buildDiscoveryStart(future, 'thermal-mix')).toThrow('recorded for rules');
    const older = copy(DISCOVERY_RECIPES[0]);
    older.rules.version--;
    expect(discoverySupported(older)).toBe(false);
    expect(() => buildDiscoveryStart(DISCOVERY_RECIPES[0], 'stingers')).toThrow(
      'Unknown discovery starting state',
    );
    expect(() => buildDiscoveryStart({} as any, 'thermal-mix')).toThrow('Invalid discovery recipe');
  });

  it('have no sandbox, global random or ecological RNG side effects', () => {
    const sandbox = new Ecosystem(DEFAULTS);
    for (let i = 0; i < 40; i++) sandbox.step();
    const before = JSON.stringify(sandbox.save()),
      random = vi.spyOn(Math, 'random');
    try {
      for (const recipe of DISCOVERY_RECIPES) {
        validateDiscoveryRecipe(recipe);
        discoveryBudget(recipe);
        for (const start of recipe.starts) buildDiscoveryStart(recipe, start.id);
      }
      observeDiscovery(sandbox);
      expect(random).not.toHaveBeenCalled();
    } finally {
      random.mockRestore();
    }
    expect(JSON.stringify(sandbox.save())).toBe(before);
  });
});

describe('fixed-seed recipe endpoints', () => {
  for (const recipe of DISCOVERY_RECIPES)
    it(`${recipe.id} reproduces its recorded real-engine endpoints`, () => {
      const outcomes = recipe.branches.map((branch) => {
        const outcome = run(recipe, branch, buildDiscoveryStart(recipe, branch.start));
        const { runtime: _runtime, ...expected } = branch.reference;
        expect(reference(outcome)).toEqual(expected);
        expect(
          classifyDiscoveryBranch(recipe, branch.id, {
            samples: outcome.samples,
            extinction: outcome.extinction,
          }),
        ).toBe(outcome.extinction ? 'extinct' : 'completed');
        return outcome;
      });
      // The two branches differ; neither is declared a winner.
      expect(outcomes[0].final).not.toBe(outcomes[1].final);
    }, 120_000);

  it('observation does not change the outcome or consume ecological RNG', () => {
    const recipe = DISCOVERY_RECIPES[2],
      branch = recipe.branches[1],
      start = buildDiscoveryStart(recipe, branch.start);
    expect(run(recipe, branch, start, false).final).toBe(run(recipe, branch, start, true).final);
  }, 60_000);

  it('shared-start recipes match the existing checkpoint comparison samples', () => {
    for (const recipe of [DISCOVERY_RECIPES[0], DISCOVERY_RECIPES[2]]) {
      const [control, treatment] = recipe.branches,
        start = buildDiscoveryStart(recipe, control.start),
        comparison = createComparison(start, {
          intervention: treatment.intervention,
          treatmentTick: recipe.interventionTick,
          horizonTick: recipe.horizonTick,
        });
      while (comparison.advance(() => 0).tick < recipe.horizonTick);
      const result = comparison.result();
      for (const [branch, compared] of [
        [control, result.control],
        [treatment, result.treatment],
      ] as const) {
        const ours = run(recipe, branch, start);
        expect(compared.state).toBe(ours.final);
        expect(sha256(compared.state)).toBe(branch.reference.checkpointSha256);
        expect(
          ours.samples.map(
            ({
              tick,
              population,
              births,
              deaths,
              meanPreference,
              meanTolerance,
              stressedFraction,
            }) => ({
              tick,
              population,
              births,
              deaths,
              meanPreference,
              meanTolerance,
              stressedFraction,
            }),
          ),
        ).toEqual(compared.samples);
        expect(compared.extinction).toEqual(ours.extinction);
      }
      comparison.dispose();
    }
  }, 120_000);
});

describe('discovery outcomes', () => {
  const recipe = DISCOVERY_RECIPES[2];
  const sample = (tick: number, population = 3): DiscoveryObservation => ({
    tick,
    population,
    births: 0,
    deaths: 0,
    food: 1,
    meanPreference: population ? 0.5 : null,
    meanTolerance: population ? 0.3 : null,
    stressedFraction: population ? 0 : null,
    leafBearers: 0,
    grazers: population,
    armoredGrazers: 0,
    stingerBearers: 0,
  });
  const ticks = discoverySampleTicks(recipe.horizonTick);

  it('classifies completed, incomplete, extinct, unsupported and missing evidence', () => {
    const full = ticks.map((tick) => sample(tick));
    expect(classifyDiscoveryBranch(recipe, 'control', { samples: full, extinction: null })).toBe(
      'completed',
    );
    expect(
      classifyDiscoveryBranch(recipe, 'control', { samples: full.slice(0, 4), extinction: null }),
    ).toBe('incomplete');
    const extinct = ticks.map((tick) => sample(tick, tick >= 60 ? 0 : 3));
    expect(
      classifyDiscoveryBranch(recipe, 'shade', {
        samples: extinct.slice(0, 5),
        extinction: { tick: 45, cause: 'energy' },
      }),
    ).toBe('extinct');
    const future = copy(recipe);
    future.rules.version++;
    expect(classifyDiscoveryBranch(future, 'control', { samples: full, extinction: null })).toBe(
      'unsupported-rules',
    );
    const missing: unknown[] = [
      null,
      { samples: [] },
      { samples: [], extinction: null },
      { samples: [sample(30)], extinction: null },
      { samples: [sample(0), { ...sample(30), food: -1 }], extinction: null },
      { samples: [...full, sample(1800)], extinction: null },
      { samples: extinct.slice(0, 5), extinction: null },
      { samples: extinct.slice(0, 5), extinction: { tick: 45 } },
      { samples: extinct.slice(0, 5), extinction: { tick: 200, cause: 'energy' } },
      { samples: extinct.slice(0, 5), extinction: { tick: 10, cause: 'energy' } },
    ];
    for (const evidence of missing)
      expect(classifyDiscoveryBranch(recipe, 'control', evidence as any)).toBe('missing-evidence');
    expect(() => classifyDiscoveryBranch(recipe, 'winner', null)).toThrow(
      'Unknown discovery branch',
    );
  });
});
