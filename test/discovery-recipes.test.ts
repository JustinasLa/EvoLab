const node = (text: string) => createHash('sha256').update(text).digest('hex');
const copy = (recipe: DiscoveryRecipe) => structuredClone(recipe) as any;

function run(
  recipe: Pick<DiscoveryRecipe, 'horizonTick' | 'interventionTick'>,
  branch: Pick<DiscoveryBranch, 'intervention'>,
  checkpoint: string,
  observe = true,
) {
  const world = Ecosystem.load(checkpoint),
    ticks = new Set(discoverySampleTicks(recipe.horizonTick)),
    samples: DiscoveryObservation[] = observe ? [observeDiscovery(world)] : [];
  let extinction: DiscoveryExtinction | null = null;
  while (world.tick < recipe.horizonTick) {
    if (world.tick === recipe.interventionTick)
      EXPERIMENT_INTERVENTIONS[branch.intervention].apply(world);
    world.step();
    if (!world.organisms.size && !extinction)
      extinction = { tick: world.tick, cause: world.lastDeath!.cause };
    if (observe && ticks.has(world.tick)) samples.push(observeDiscovery(world));
  }
  return { samples, extinction, final: JSON.stringify(world.save()) };
}
const reference = (outcome: ReturnType<typeof run>): Omit<DiscoveryReference, 'runtime'> => ({
  samples: outcome.samples.length,
  samplesSha256: sha256(JSON.stringify(outcome.samples)),
  endpoint: outcome.samples.at(-1)!,
  extinction: outcome.extinction,
  checkpointSha256: sha256(outcome.final),
});

